#!/usr/bin/env python3
"""Write the proto3 JSON fixtures for test/data.

The oracle is google.protobuf's `json_format`, which is the reference
implementation, at the same version as the protoc in this shell. Each source is
the text-format message that `just proto` turns into a binary fixture, so a
fixture pair describes one message in two encodings, from two implementations.

`just protojson` writes the output to test/data/json.txtar. Nothing here
inspects the Zig code: the point is a second opinion.
"""

import pathlib
import subprocess
import sys
import tempfile

from google.protobuf import (
    descriptor_pb2,
    descriptor_pool,
    json_format,
    message_factory,
    text_format,
)


def compact(text: str) -> str:
    """Remove whitespace outside JSON strings.

    The reference printer writes `indent=2` by default. Python's `json.dumps`
    with no indent adds a space after each `,` and `:`, and those spaces say
    nothing. Key order and every value stay as the printer wrote them.
    """
    out = []
    in_string = False
    escaped = False
    for ch in text:
        if in_string:
            out.append(ch)
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                in_string = False
            continue
        if ch == '"':
            in_string = True
            out.append(ch)
        elif ch in " \t\n\r":
            continue
        else:
            out.append(ch)
    return "".join(out)


def headers(text: str) -> tuple[str, str]:
    """The `# proto:` and `# type:` lines that every fixture starts with."""
    proto = message = ""
    for line in text.splitlines():
        if line.startswith("# proto: "):
            proto = line[len("# proto: ") :]
        elif line.startswith("# type: "):
            message = line[len("# type: ") :]
    return proto, message


def pool_for(data: pathlib.Path, sources: list[pathlib.Path]) -> descriptor_pool.DescriptorPool:
    """A pool holding every proto under test/data, imported files included."""
    protos = sorted({headers(p.read_text())[0] for p in sources})
    if not protos:
        raise SystemExit("no .txt fixtures with a '# proto:' header")

    pool = descriptor_pool.DescriptorPool()
    with tempfile.TemporaryDirectory() as tmp:
        out = pathlib.Path(tmp) / "descriptors.pb"
        subprocess.run(
            [
                "protoc",
                f"-I{data}",
                f"--descriptor_set_out={out}",
                "--include_imports",
                *protos,
            ],
            check=True,
        )
        found = descriptor_pb2.FileDescriptorSet()
        found.ParseFromString(out.read_bytes())

    # protoc writes a file after the files it imports.
    for file in found.file:
        pool.Add(file)
    return pool


def main() -> int:
    data = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else pathlib.Path(__file__).parent)
    sources = sorted(data.glob("*/*.txt"))
    pool = pool_for(data, sources)

    print("Generated by 'just protojson'. Each section is the proto3 JSON that")
    print("google.protobuf's json_format wrote for a text-format message, with")
    print("the whitespace that means nothing removed.")

    for source in sources:
        text = source.read_text()
        proto, message = headers(text)
        if not proto or not message:
            raise SystemExit(f"{source}: needs '# proto: <file>' and '# type: <message>'")

        descriptor = pool.FindMessageTypeByName(message)
        cls = message_factory.GetMessageClass(descriptor)
        value = cls()
        text_format.Parse(text, value)

        printed = json_format.MessageToJson(
            value,
            preserving_proto_field_name=False,
            indent=None,
        )

        print()
        print(f"-- {source.relative_to(data).with_suffix('.json')} --")
        print(compact(printed))
    return 0


if __name__ == "__main__":
    sys.exit(main())
